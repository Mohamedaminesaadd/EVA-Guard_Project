const SVG_NS = 'http://www.w3.org/2000/svg';

/** Lightweight Lucide icon renderer (no Angular wrapper dependency, works with any Angular version). */
@Component({
  selector: 'app-icon',
  template: '',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: {
    'aria-hidden': 'true',
    '[style.width.px]': 'size()',
    '[style.height.px]': 'size()',
  },
  styles: [':host{display:inline-flex;flex-shrink:0;line-height:0;vertical-align:middle}:host ::ng-deep svg{width:100%;height:100%}'],
})
export class IconComponent {
  readonly name = input.required<string>();
  readonly size = input(16);
  readonly strokeWidth = input(2);

  private readonly host = inject<ElementRef<HTMLElement>>(ElementRef);

  constructor() {
    effect(() => {
      const node = ICONS[this.name()] ?? CircleQuestionMark;
      const svg = document.createElementNS(SVG_NS, 'svg');
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', String(this.strokeWidth()));
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
      for (const [tag, attrs] of node) {
        const el = document.createElementNS(SVG_NS, tag);
        for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v));
        svg.appendChild(el);
      }
      this.host.nativeElement.replaceChildren(svg);
    });
  }
}
