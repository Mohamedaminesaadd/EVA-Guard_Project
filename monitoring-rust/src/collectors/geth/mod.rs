use serde_json::{json, Value};

/// Parses an Ethereum JSON-RPC quantity (e.g. "0x10") into a u64.
///
/// Strict on purpose: requires the lowercase "0x" prefix and at least one
/// hexadecimal digit. Signs, whitespace and u64 overflow are rejected.
pub(crate) fn parse_hex_u64(value: &str) -> Option<u64> {
    let digits = value.strip_prefix("0x")?;

    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }

    u64::from_str_radix(digits, 16).ok()
}

/// Reads a hexadecimal quantity stored as a JSON string under `field`.
///
/// Returns None if `object` is not an object, the field is missing,
/// is not a string, or is not a valid quantity.
pub(crate) fn hex_field(object: &Value, field: &str) -> Option<u64> {
    object
        .get(field)
        .and_then(Value::as_str)
        .and_then(parse_hex_u64)
}

/// Single entry point used by the collectors for raw JSON-RPC calls.
///
/// Errors are intentionally flattened to None: collectors report missing
/// measurements as None instead of failing the whole collection cycle.
pub(crate) async fn call_value(
    client: &GethClient,
    method: &str,
    params: Vec<Value>,
) -> Option<Value> {
    client
        .call::<Value>(method, params)
        .await
        .ok()
        .map(|response| response.value)
}

/// Fetches the latest block (transaction hashes only) in one request.
///
/// Using the `latest` tag avoids the race of calling `eth_blockNumber`
/// first and `eth_getBlockByNumber` afterwards, and halves the RPC traffic
/// generated by the monitoring itself.
///
/// Returns None if the call fails or the node answers `null`.
pub(crate) async fn fetch_latest_block(client: &GethClient) -> Option<Value> {
    let params = vec![json!("latest"), json!(false)];
    let block = call_value(client, "eth_getBlockByNumber", params).await?;

    (!block.is_null()).then_some(block)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_regular_quantities() {
        assert_eq!(parse_hex_u64("0x10"), Some(16));
        assert_eq!(parse_hex_u64("0x0"), Some(0));
        assert_eq!(parse_hex_u64("0x6553f100"), Some(1_700_000_000));
        assert_eq!(parse_hex_u64("0xFF"), Some(255));
    }

    #[test]
    fn parses_u64_max() {
        assert_eq!(parse_hex_u64("0xffffffffffffffff"), Some(u64::MAX));
    }

    #[test]
    fn rejects_u64_overflow() {
        assert_eq!(parse_hex_u64("0x10000000000000000"), None);
    }

    #[test]
    fn rejects_missing_prefix() {
        assert_eq!(parse_hex_u64("10"), None);
        assert_eq!(parse_hex_u64(""), None);
    }

    #[test]
    fn rejects_empty_digits() {
        assert_eq!(parse_hex_u64("0x"), None);
    }

    #[test]
    fn rejects_invalid_digits() {
        assert_eq!(parse_hex_u64("0xxyz"), None);
        assert_eq!(parse_hex_u64("0x12g"), None);
    }

    #[test]
    fn rejects_signs_and_whitespace() {
        // u64::from_str_radix alone would accept the leading '+'.
        assert_eq!(parse_hex_u64("0x+10"), None);
        assert_eq!(parse_hex_u64("0x-10"), None);
        assert_eq!(parse_hex_u64(" 0x10"), None);
        assert_eq!(parse_hex_u64("0x10 "), None);
    }

    #[test]
    fn hex_field_reads_string_quantities() {
        let block = json!({ "number": "0x1b4", "timestamp": "0x0" });

        assert_eq!(hex_field(&block, "number"), Some(436));
        assert_eq!(hex_field(&block, "timestamp"), Some(0));
    }

    #[test]
    fn hex_field_rejects_missing_or_wrong_types() {
        let block = json!({ "number": 436, "bad": "0xzz", "nothing": null });

        assert_eq!(hex_field(&block, "absent"), None);
        assert_eq!(hex_field(&block, "number"), None);
        assert_eq!(hex_field(&block, "bad"), None);
        assert_eq!(hex_field(&block, "nothing"), None);
    }

    #[test]
    fn hex_field_handles_non_objects() {
        assert_eq!(hex_field(&Value::Null, "number"), None);
        assert_eq!(hex_field(&json!([]), "number"), None);
        assert_eq!(hex_field(&json!("0x10"), "number"), None);
    }
}
