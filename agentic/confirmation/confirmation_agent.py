
import asyncio
import json
import logging
from typing import Any

from pydantic import BaseModel, Field
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import PydanticOutputParser
from langchain_ollama import ChatOllama

from knowledge_base.retrieval.query_engine import KnowledgeQueryEngine

from agentic.schemas import (
    Incident,
    Hypothesis,
    Confirmation,
    Evidence,
    RAGSource,
    Verdict,
)

from .prompts import SYSTEM_PROMPT, USER_PROMPT


logger = logging.getLogger(__name__)


class ConfirmationAssessment(BaseModel):
    """
    Internal assessment generated by the LLM.
    It is not the final deterministic verdict.
    """

    reasoning: str

    supporting_evidence: list[Evidence] = Field(
        default_factory=list
    )

    contradicting_evidence: list[Evidence] = Field(
        default_factory=list
    )

    alternative_explanations: list[str] = Field(
        default_factory=list
    )

    confidence: float = Field(
        ge=0.0,
        le=1.0
    )

    recommendations: list[str] = Field(
        default_factory=list
    )


class ConfirmationAgent:

    def __init__(
        self,
        model: str = "qwen2.5:14b",
        base_url: str = "http://localhost:11434",
        top_k: int = 5,
    ):

        logger.info("Initializing Confirmation Agent...")

        self.llm = ChatOllama(
            model=model,
            base_url=base_url,
            temperature=0.1,
        )

        self.rag = KnowledgeQueryEngine(
            model=model,
            base_url=base_url,
            top_k=top_k,
        )

        self.parser = PydanticOutputParser(
            pydantic_object=ConfirmationAssessment
        )

        self.prompt = ChatPromptTemplate.from_messages([
            ("system", SYSTEM_PROMPT),
            ("human", USER_PROMPT),
        ])

        logger.info("Confirmation Agent initialized.")

    # ==========================================
    # SNAPSHOT METRICS
    # ==========================================

    def _flatten_metrics(
        self,
        data: dict[str, Any],
        prefix: str = "",
    ) -> dict[str, Any]:

        metrics = {}

        for key, value in data.items():

            metric_name = (
                f"{prefix}.{key}" if prefix else key
            )

            if isinstance(value, dict):

                metrics.update(
                    self._flatten_metrics(
                        value,
                        metric_name,
                    )
                )

            elif isinstance(value, (int, float)) and not isinstance(
                value, bool
            ):

                metrics[metric_name] = value

            elif isinstance(value, (str, bool)):

                metrics[metric_name] = value

        return metrics

    def _same_value(self, first, second) -> bool:

        if first == second:
            return True

        if isinstance(first, (int, float)) and isinstance(
            second, (int, float)
        ):
            return float(first) == float(second)

        return str(first) == str(second)

    def _validate_evidence(
        self,
        evidence_list: list[Evidence],
        snapshot_metrics: dict[str, Any],
    ) -> list[Evidence]:

        validated = []

        for evidence in evidence_list:

            metric = evidence.metric

            if not metric:
                continue

            if metric not in snapshot_metrics:
                continue

            actual_value = snapshot_metrics[metric]

            if not self._same_value(
                evidence.observed_value,
                actual_value,
            ):
                continue

            validated.append(
                Evidence(
                    description=evidence.description,
                    metric=metric,
                    observed_value=actual_value,
                    expected_value=evidence.expected_value,
                )
            )

        return validated

    def _merge_evidence(
        self,
        first: list[Evidence],
        second: list[Evidence],
    ) -> list[Evidence]:

        merged = {}
        
        for evidence in first + second:

            key = (
                evidence.metric,
                str(evidence.observed_value),
            )

            merged[key] = evidence

        return list(merged.values())

    # ==========================================
    # RAG
    # ==========================================

    def _build_rag_question(
        self,
        incident: Incident,
        hypothesis: Hypothesis,
    ) -> str:

        attack_type = hypothesis.attack_hypothesis.value

        if attack_type == "RPC_FLOODING":

            return """
Independently assess the technical indicators of Ethereum RPC flooding.

Explain:
- RPC request rates and their interpretation.
- RPC latency and failed requests.
- Network and TCP indicators.
- Possible benign explanations.
- Evidence needed to distinguish overload from an attack.

Do not invent numerical thresholds.
"""

        return """
Independently assess the technical indicators of Ethereum Eclipse attacks.

Explain:
- Peer count and peer churn.
- Network isolation indicators.
- Blockchain synchronization and block progression.
- Possible benign explanations.
- Evidence needed to distinguish an Eclipse attack from normal connectivity problems.

Do not invent numerical thresholds.
"""

    async def _retrieve_knowledge(
        self,
        incident: Incident,
        hypothesis: Hypothesis,
    ) -> dict:

        question = self._build_rag_question(
            incident,
            hypothesis,
        )

        return await asyncio.to_thread(
            self.rag.query,
            question=question,
            category="attacks",
            k=5,
        )

    def _convert_sources(
        self,
        sources: list[dict],
    ) -> list[RAGSource]:

        result = []

        for source in sources:

            result.append(
                RAGSource(
                    source_id=str(
                        source.get("source_id", "")
                    ),
                    file_name=source.get(
                        "file_name", "unknown"
                    ),
                    source=source.get(
                        "source", ""
                    ),
                    category=source.get("category"),
                    distance=source.get("distance"),
                )
            )

        return result

    # ==========================================
    # DETERMINISTIC VERDICT
    # ==========================================

    def _determine_verdict(
        self,
        incident: Incident,
        hypothesis: Hypothesis,
        supporting: list[Evidence],
        contradicting: list[Evidence],
    ) -> Verdict:

        if (
            hypothesis.incident_id != incident.incident_id
            or hypothesis.attack_hypothesis != incident.attack_type
        ):
            return Verdict.INCONCLUSIVE

        if not supporting:
            return Verdict.INCONCLUSIVE

        if len(contradicting) >= len(supporting):
            return Verdict.INCONCLUSIVE

        # Without independent ground truth or a validated
        # historical baseline, the attack cannot be confirmed.
        return Verdict.SUSPECTED

    # ==========================================
    # MAIN INVESTIGATION
    # ==========================================

    async def aconfirm(
        self,
        incident: Incident,
        hypothesis: Hypothesis,
    ) -> Confirmation:

        if hypothesis.incident_id != incident.incident_id:
            raise ValueError(
                "Incident ID does not match hypothesis ID."
            )

        logger.info(
            "Starting confirmation for incident %s",
            incident.incident_id,
        )

        # 1. Extract metrics
        snapshot_metrics = self._flatten_metrics(
            incident.observation_snapshot
        )

        # 2. Validate Agent 1 evidence
        verified_hypothesis_support = (
            self._validate_evidence(
                hypothesis.supporting_evidence,
                snapshot_metrics,
            )
        )

        verified_hypothesis_contradictions = (
            self._validate_evidence(
                hypothesis.contradicting_evidence,
                snapshot_metrics,
            )
        )

        # 3. Retrieve independent technical knowledge
        rag_result = await self._retrieve_knowledge(
            incident,
            hypothesis,
        )

        rag_answer = rag_result.get(
            "answer", "No technical knowledge retrieved."
        )

        rag_sources_raw = rag_result.get(
            "sources", []
        )

        rag_sources = self._convert_sources(
            rag_sources_raw
        )

        # 4. Build prompt context
        context = {
            "incident": json.dumps(
                incident.model_dump(mode="json"),
                indent=2,
            ),
            "hypothesis": json.dumps(
                hypothesis.model_dump(mode="json"),
                indent=2,
            ),
            "snapshot_metrics": json.dumps(
                snapshot_metrics,
                indent=2,
            ),
            "hypothesis_evidence": json.dumps(
                {
                    "supporting": [
                        e.model_dump(mode="json")
                        for e in verified_hypothesis_support
                    ],
                    "contradicting": [
                        e.model_dump(mode="json")
                        for e in verified_hypothesis_contradictions
                    ],
                },
                indent=2,
            ),
            "rag_answer": rag_answer,
            "rag_sources": json.dumps(
                [
                    s.model_dump(mode="json")
                    for s in rag_sources
                ],
                indent=2,
            ),
            "format_instructions": (
                self.parser.get_format_instructions()
            ),
        }

        messages = self.prompt.format_messages(
            **context
        )

        # 5. Independent LLM assessment
        response = await self.llm.ainvoke(messages)

        assessment = self.parser.parse(
            str(response.content)
        )

        # 6. Validate all LLM evidence against real metrics
        llm_support = self._validate_evidence(
            assessment.supporting_evidence,
            snapshot_metrics,
        )

        llm_contradictions = self._validate_evidence(
            assessment.contradicting_evidence,
            snapshot_metrics,
        )

        # 7. Merge verified evidence
        supporting = self._merge_evidence(
            verified_hypothesis_support,
            llm_support,
        )

        contradicting = self._merge_evidence(
            verified_hypothesis_contradictions,
            llm_contradictions,
        )

        # 8. Apply deterministic decision policy
        verdict = self._determine_verdict(
            incident,
            hypothesis,
            supporting,
            contradicting,
        )

        # 9. Construct final result
        confirmation = Confirmation(
            incident_id=incident.incident_id,
            verdict=verdict,
            confidence=assessment.confidence,
            supporting_evidence=supporting,
            contradicting_evidence=contradicting,
            alternative_explanations=(
                assessment.alternative_explanations
            ),
            rag_sources=rag_sources,
            reasoning=assessment.reasoning,
            recommendations=assessment.recommendations,
            status="COMPLETED",
        )

        logger.info(
            "Confirmation completed: %s - %s",
            incident.incident_id,
            verdict.value,
        )

        return confirmation
